/** 足の束ね（#200。model/bars.ts）: 立会に合わせた 4 時間足と週足。値はすべて架空 */
import { describe, expect, it } from 'vitest';
import { fourHourStart, resample4h, resampleWeekly, weekStart } from '../../model/bars';

const jst = (s: string) => Date.parse(`${s}+09:00`) / 1000;
const iso = (t: number) => new Date((t + 9 * 3600) * 1000).toISOString().slice(0, 16);

describe('4 時間足の区切り（立会に合わせる）', () => {
  it.each([
    ['2026-10-14T08:00', '2026-10-14T08:00'],
    ['2026-10-14T11:00', '2026-10-14T08:00'],
    ['2026-10-14T12:00', '2026-10-14T12:00'],
    ['2026-10-14T15:00', '2026-10-14T12:00'],
    ['2026-10-14T16:00', '2026-10-14T12:00'],
    ['2026-10-14T17:00', '2026-10-14T17:00'],
    ['2026-10-14T20:00', '2026-10-14T17:00'],
    ['2026-10-14T21:00', '2026-10-14T21:00'],
    ['2026-10-14T23:00', '2026-10-14T21:00'],
    ['2026-10-15T00:00', '2026-10-14T21:00'],
    ['2026-10-15T01:00', '2026-10-15T01:00'],
    ['2026-10-15T05:00', '2026-10-15T01:00'],
    ['2026-10-15T07:00', '2026-10-15T01:00'],
  ])('%s → %s', (t, want) => {
    expect(iso(fourHourStart(jst(`${t}:00`)))).toBe(want);
  });
  it('1 時間足の途中の時刻も同じ足', () => {
    expect(fourHourStart(jst('2026-10-14T09:59:59'))).toBe(jst('2026-10-14T08:00:00'));
  });
  it('1 取引日（日中 8 本 + 夜間 13 本の 1 時間足）→ 5 本。夜間の最後は 01:00〜06:00 の 5 本ぶん', () => {
    const hours = [8, 9, 10, 11, 12, 13, 14, 15];
    const night = [17, 18, 19, 20, 21, 22, 23];
    const after = [0, 1, 2, 3, 4, 5];
    const bars = [
      ...hours.map((h) => jst(`2026-10-14T${String(h).padStart(2, '0')}:00:00`)),
      ...night.map((h) => jst(`2026-10-14T${h}:00:00`)),
      ...after.map((h) => jst(`2026-10-15T0${h}:00:00`)),
    ].map((t, i) => ({
      t,
      o: 100 + i,
      h: 110 + i,
      l: 90 + i,
      c: 101 + i,
      m: i < 8 ? '2026-12' : '2027-03',
    }));
    const out = resample4h(bars);
    expect(out.map((b) => iso(b.t))).toEqual([
      '2026-10-14T08:00',
      '2026-10-14T12:00',
      '2026-10-14T17:00',
      '2026-10-14T21:00',
      '2026-10-15T01:00',
    ]);
    // 始値 = 最初、終値 = 最後、高安 = 最大・最小、他のキー = 最後の足
    expect(out[0]).toEqual({
      t: jst('2026-10-14T08:00:00'),
      o: 100,
      h: 113,
      l: 90,
      c: 104,
      m: '2026-12',
    });
    expect(out[3]).toMatchObject({ o: 112, c: 116 });
    expect(out[4]).toMatchObject({ o: 116, h: 130, c: 121, m: '2027-03' });
    // 日中の終わり（15 時）と夜間の始まり（17 時）は別の足、限月交代（17:00）は境
    expect(out[1]?.m).toBe('2026-12');
    expect(out[2]?.m).toBe('2027-03');
    // 入力を変えない
    expect(bars[1]?.t).toBe(jst('2026-10-14T09:00:00'));
  });
});

describe('週足（JST の月曜始まり）', () => {
  it('週の始まり', () => {
    // 2026-10-12 は月曜
    expect(iso(weekStart(jst('2026-10-12T00:00:00')))).toBe('2026-10-12T00:00');
    expect(iso(weekStart(jst('2026-10-16T23:00:00')))).toBe('2026-10-12T00:00');
    expect(iso(weekStart(jst('2026-10-18T12:00:00')))).toBe('2026-10-12T00:00');
    expect(iso(weekStart(jst('2026-10-19T00:00:00')))).toBe('2026-10-19T00:00');
  });
  it('日足 → 週足（足の t は週の最初の日足）', () => {
    const days = ['2026-10-13', '2026-10-14', '2026-10-16', '2026-10-19', '2026-10-20'];
    const bars = days.map((d, i) => ({
      t: jst(`${d}T00:00:00`),
      o: 10 + i,
      h: 20 + i,
      l: 5 - i,
      c: 11 + i,
    }));
    const out = resampleWeekly(bars);
    expect(out).toEqual([
      { t: jst('2026-10-13T00:00:00'), o: 10, h: 22, l: 3, c: 13 },
      { t: jst('2026-10-19T00:00:00'), o: 13, h: 24, l: 1, c: 15 },
    ]);
  });
});
